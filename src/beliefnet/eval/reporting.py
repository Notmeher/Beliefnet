"""Standardized result persistence + a single aggregated markdown report.

Every experiment writes a JSON payload under ``results/<name>/result.json`` via
``save_result``. ``build_details_md`` scans all such payloads and renders one
``results/details_results.md`` so the whole suite is reported in one place.

Payload convention (all keys optional except handled gracefully):
    {
      "title":    str,
      "question": str,
      "config":   dict[str, Any],
      "summary":  dict[str, scalar],
      "tables":   dict[str, list[dict]],   # name -> rows
      "notes":    list[str],
    }
"""
from __future__ import annotations

import datetime
import json
from pathlib import Path
from typing import Any


def _now() -> str:
    return datetime.datetime.now().isoformat(timespec="seconds")


def save_result(results_dir: str | Path, name: str, payload: dict) -> Path:
    """Write ``results/<name>/result.json`` and return its path."""
    exp_dir = Path(results_dir) / name
    exp_dir.mkdir(parents=True, exist_ok=True)
    out = {"experiment": name, "generated": _now(), **payload}
    path = exp_dir / "result.json"
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2)
    return path


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def _render_table(rows: list[dict]) -> list[str]:
    if not rows:
        return ["_(no rows)_", ""]
    cols: list[str] = []
    for r in rows:
        for k in r:
            if k not in cols:
                cols.append(k)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(_fmt(r.get(c, "")) for c in cols) + " |")
    lines.append("")
    return lines


def build_details_md(results_dir: str | Path) -> Path:
    """Aggregate every ``results/*/result.json`` into details_results.md."""
    results_dir = Path(results_dir)
    payloads = []
    for p in sorted(results_dir.glob("*/result.json")):
        try:
            payloads.append(json.loads(p.read_text(encoding="utf-8")))
        except json.JSONDecodeError:
            continue

    L: list[str] = [
        "# BeliefNet — Detailed Results",
        "",
        "> Auto-generated by `scripts/build_report.py`; overwritten each run.",
        "",
        f"_Generated: {_now()}_",
        "",
        "## Contents",
        "",
    ]
    for pl in payloads:
        L.append(f"- {pl.get('title', pl['experiment'])} (`{pl['experiment']}`)")
    L.append("")

    for pl in payloads:
        L.append(f"## {pl.get('title', pl['experiment'])}")
        L.append("")
        L.append(f"_id: `{pl['experiment']}` — generated {pl.get('generated', '?')}_")
        L.append("")
        if pl.get("question"):
            L.append(f"**Question.** {pl['question']}")
            L.append("")
        if pl.get("config"):
            L.append("**Config:** "
                     + ", ".join(f"`{k}={v}`" for k, v in pl["config"].items()))
            L.append("")
        if pl.get("summary"):
            L.append("**Summary**")
            L.append("")
            for k, v in pl["summary"].items():
                L.append(f"- {k}: {_fmt(v)}")
            L.append("")
        for tname, rows in (pl.get("tables") or {}).items():
            L.append(f"### {tname}")
            L.append("")
            L.extend(_render_table(rows))
        for note in (pl.get("notes") or []):
            L.append(f"> {note}")
            L.append("")

    out = results_dir / "details_results.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    return out
